"""SMT implication checker.

A `format: "smt-implication"` certificate must carry a script that is the exact
canonical encoding of the obligation formula:

    premise_1 ... premise_n  |-  goal

The script is regenerated by :mod:`checkers.expr` from the proof graph.  A
planner-supplied unsat script is never trusted merely because z3 says UNSAT;
`(assert false)` therefore cannot discharge an arbitrary guarantee.

The independent checker is z3.  Only `unsat` is accepted.
"""
from __future__ import annotations

import z3

from . import expr


def _run(script: str, timeout_ms: int | None = None) -> tuple[bool, str]:
    limit = timeout_ms or 30_000
    solver = z3.Solver()
    try:
        solver.set(timeout=int(limit))
        solver.from_string(script)
        result = solver.check()
    except z3.Z3Exception as exc:
        return False, f"z3 parse/check error: {exc}"
    except Exception as exc:  # noqa: BLE001
        return False, f"checker error: {exc}"

    if result == z3.unsat:
        return True, "unsat"
    if result == z3.sat:
        return False, "sat: implication does not hold"
    return False, f"unknown ({solver.reason_unknown()})"


def check(payload: dict, timeout_ms: int | None = None) -> tuple[bool, str]:
    """Legacy script-only entry point.

    This function is intentionally *not* sufficient for a CHECKED obligation.
    The kernel uses :func:`check_implication`, which binds the script to the
    premise/goal formulas.  Keep this helper for explicit diagnostic use only.
    """
    if not isinstance(payload, dict):
        return False, "payload must be an object"
    script = payload.get("smt2")
    if not isinstance(script, str) or not script.strip():
        return False, "payload.smt2 is required"
    return _run(script, timeout_ms or payload.get("timeout_ms"))


def check_implication(
    premises: list[str],
    goal: str,
    script: str,
    timeout_ms: int | None = None,
) -> tuple[bool, str]:
    """Check a certificate against the canonical encoding of an obligation."""
    ok, expected, detail = expr.script_matches(script, premises, goal)
    if not ok:
        if expected:
            return False, f"{detail}; expected script:\n{expected}"
        return False, detail
    return _run(expected, timeout_ms)
