"""Decomposition planner: turn a lemma-chain manifest into a PCD proposal.

The plain template planner treats every bad property as an independent atom and
composes them by conjunction.  That is sound but it does not carry *why* a set
of helpers is sufficient.  This planner reads a small manifest that declares

  * helper lemmas and the lemmas they depend on,
  * target properties and the lemmas they consume,
  * one or more cuts whose entry/step/exit/link facts partition the chain,
  * an optional root target.

It emits one replay node per property (so the engine evidence is unchanged),
one CHECKED interface node per cut, and a CHECKED root.  The cut interface is
consumed by the root and its premises are the named lemmas/targets.  The proof
graph therefore records the decomposition instead of flattening it.

An optional ``sets`` block partitions the lemmas/targets by engine method and
lets a later set consume an earlier set's proved lemma as a checked premise.
The manifest is still data, not code: a planner cannot inject an arbitrary SMT
script or an assumption.  The interface/root scripts are the canonical
implication scripts generated by ``checkers.expr``.
"""
from __future__ import annotations

import re
from typing import Any

from checkers import expr as expr_mod

from .core import PcdError


def _sanitize(name: str, fallback: str) -> str:
    out = re.sub(r"[^A-Za-z0-9_.-]+", "_", name).strip("_.-")
    return out or fallback


def _timeout_for(case: dict[str, Any], engine: str) -> int:
    budgets = case.get("budgets", {})
    value = budgets.get("engine_seconds", {}).get(engine)
    if value is None:
        value = budgets.get("total_seconds", 1)
    return max(1, int(value))


def _property_index(context: dict[str, Any], name: str) -> tuple[int, dict[str, Any]]:
    matches = [p for p in context["model"].get("properties", []) if str(p.get("name")) == name]
    if not matches:
        raise PcdError(f"decomposition: property {name!r} is not in the model sketch")
    if len(matches) > 1:
        raise PcdError(f"decomposition: property {name!r} is ambiguous in the model sketch")
    return int(matches[0]["index"]), matches[0]


def _replay_node(
    *,
    node_id: str,
    prop: dict[str, Any],
    statement: str,
    role: str,
    kind: str,
    phase: str,
    requires: list[dict[str, Any]],
    guarantee: str,
    symbol: str,
    timeout_s: int,
    helper: dict[str, Any] | None,
    backend: str = "cill",
    engine: str = "ric3",
) -> dict[str, Any]:
    hint: dict[str, Any] = {
        "evidence": "REPLAY",
        "format": "replay",
        "goal": guarantee,
        "engine": engine,
        "backend": backend,
        "timeout_s": timeout_s,
        "property_index": prop["index"],
        "assertion_name": str(prop.get("name", "")) or None,
        "note": (
            "cill checks all properties in one trusted inductiveness run"
            if backend == "cill"
            else f"{backend} checks this property separately and reports a clean UNKNOWN on budget exhaustion"
        ),
    }
    if prop.get("assertion_file"):
        hint["assertion_file"] = prop["assertion_file"]
    if not hint.get("assertion_name"):
        hint.pop("assertion_name", None)
    node: dict[str, Any] = {
        "id": node_id,
        "role": role,
        "kind": kind,
        "phase": phase,
        "statement": statement,
        "requires": requires,
        "provides": [{
            "name": guarantee, "expr": symbol, "sort": "Bool",
            "binding": {"kind": "btor-bad", "property": str(prop["name"])},
        }],
        "certificate_hint": hint,
    }
    if helper is not None:
        node["helper"] = helper
    return node


def _conjunction(exprs: list[str]) -> str:
    if not exprs:
        raise PcdError("decomposition: cannot form an empty conjunction")
    if len(exprs) == 1:
        return exprs[0]
    return "(and " + " ".join(exprs) + ")"


def _premise(node_id: str, guarantee: str) -> dict[str, str]:
    return {"node": node_id, "guarantee": guarantee}


_SET_METHODS = {"cill", "portfolio", "ic3", "kind", "bmc"}


def _set_configuration(
    spec: dict[str, Any],
    lemma_ids: list[str],
    target_ids: list[str],
) -> tuple[dict[str, dict[str, Any]], dict[str, dict[str, Any]], list[dict[str, Any]]]:
    """Resolve the optional ``sets`` block into per-item method/assumption data.

    A set is a proof partition, not a new trust boundary.  Its ``method`` is a
    trusted engine backend (``cill``, ``portfolio``, ``ic3``, ...), and its
    ``assumes`` list may name only lemmas proved by an earlier set.  The
    assumptions become ordinary proof-graph premises, so a downstream engine
    can use the earlier result as a checked blackbox without adding a TCB.
    """
    raw = spec.get("sets")
    if raw is None:
        return {}, {}, []
    if not isinstance(raw, list) or not raw:
        raise PcdError("decomposition: sets must be a non-empty array when present")

    lemma_cfg: dict[str, dict[str, Any]] = {}
    target_cfg: dict[str, dict[str, Any]] = {}
    records: list[dict[str, Any]] = []
    known_lemmas = set(lemma_ids)
    known_targets = set(target_ids)
    overlap = known_lemmas & known_targets
    if overlap:
        raise PcdError(
            "decomposition: ids used as both lemma and target: " + ", ".join(sorted(overlap))
        )
    seen: dict[str, str] = {}

    def add_member(member: str, where: str, sid: str) -> None:
        if member in seen:
            raise PcdError(
                f"decomposition: {where} {member!r} appears in both set {seen[member]!r} and {sid!r}"
            )
        seen[member] = sid

    for i, item in enumerate(raw):
        if not isinstance(item, dict):
            raise PcdError("decomposition: each set must be an object")
        sid = _sanitize(str(item.get("id", "")), f"set_{i}")
        if any(rec["id"] == sid for rec in records):
            raise PcdError(f"decomposition: duplicate set id {sid!r}")
        method = str(item.get("method") or item.get("backend") or "cill")
        if method not in _SET_METHODS:
            raise PcdError(f"decomposition: set {sid!r} has unsupported method {method!r}")
        members = [str(x) for x in item.get("lemmas", [])]
        targets = [str(x) for x in item.get("targets", [])]
        assumes = [str(x) for x in item.get("assumes", [])]
        if not members and not targets:
            raise PcdError(f"decomposition: set {sid!r} has no lemma or target")
        for member in members:
            if member not in known_lemmas:
                raise PcdError(f"decomposition: set {sid!r} names unknown lemma {member!r}")
            add_member(member, "lemma", sid)
            lemma_cfg[member] = {
                "set": sid,
                "order": i,
                "backend": method,
                "assumes": assumes,
            }
        for member in targets:
            if member not in known_targets:
                raise PcdError(f"decomposition: set {sid!r} names unknown target {member!r}")
            add_member(member, "target", sid)
            target_cfg[member] = {
                "set": sid,
                "order": i,
                "backend": method,
                "assumes": assumes,
            }
        records.append(
            {
                "id": sid,
                "method": method,
                "lemmas": members,
                "targets": targets,
                "assumes": assumes,
            }
        )

    covered = set(lemma_cfg) | set(target_cfg)
    missing = (set(lemma_ids) | set(target_ids)) - covered
    if missing:
        raise PcdError(
            "decomposition: every lemma and target must belong to a set; missing: "
            + ", ".join(sorted(missing))
        )

    # An assumption is a proved lemma from an earlier set.  Forward or
    # same-set assumptions are rejected: they would either be circular or
    # would ask an unproved result to carry the proof.
    for cfg in list(lemma_cfg.values()) + list(target_cfg.values()):
        sid = cfg["set"]
        order = cfg["order"]
        for assumed in cfg["assumes"]:
            if assumed not in known_lemmas:
                raise PcdError(
                    f"decomposition: set {sid!r} assumes {assumed!r}, which is not a lemma"
                )
            source = lemma_cfg.get(assumed)
            if source is None:
                raise PcdError(
                    f"decomposition: set {sid!r} assumes {assumed!r}, which is not in any set"
                )
            if source["set"] == sid:
                raise PcdError(
                    f"decomposition: set {sid!r} assumes its own lemma {assumed!r}"
                )
            if source["order"] >= order:
                raise PcdError(
                    f"decomposition: set {sid!r} assumes {assumed!r} from a later set "
                    f"({source['set']!r}); assumptions must point backwards"
                )
    return lemma_cfg, target_cfg, records


def decomposition_proposals(
    context: dict[str, Any],
    context_sha256: str,
    spec: dict[str, Any],
) -> dict[str, Any]:
    """Build a proposal from a ``pcd-decomposition/0.1`` manifest."""
    case = context["case"]
    if spec.get("schema_version") != "pcd-decomposition/0.1":
        raise PcdError("decomposition: schema_version must be pcd-decomposition/0.1")
    if spec.get("case") not in (None, case["id"]):
        raise PcdError(
            f"decomposition: case {spec.get('case')!r} does not match sketch case {case['id']!r}"
        )

    timeout_s = _timeout_for(case, "ric3")
    nodes: list[dict[str, Any]] = []
    by_id: dict[str, dict[str, Any]] = {}
    symbols: dict[str, str] = {}
    guarantee_by_node: dict[str, str] = {}
    node_id_by_manifest: dict[str, str] = {}
    property_nodes: dict[str, str] = {}

    def add_node(node: dict[str, Any]) -> None:
        nid = node["id"]
        if nid in by_id:
            raise PcdError(f"decomposition: duplicate node id {nid!r}")
        by_id[nid] = node
        nodes.append(node)

    def prem(req_id: str) -> dict[str, str]:
        actual = node_id_by_manifest.get(req_id, req_id)
        if actual not in by_id:
            raise PcdError(f"decomposition: unknown lemma/target id {req_id!r}")
        return _premise(actual, guarantee_by_node[actual])

    lemma_items = list(spec.get("lemmas", []))
    target_items = list(spec.get("targets", []))
    lemma_ids = [_sanitize(str(item.get("id", "")), "lemma") for item in lemma_items]
    manifest_target_ids = [_sanitize(str(item.get("id", "")), "target") for item in target_items]
    lemma_cfg, target_cfg, set_records = _set_configuration(spec, lemma_ids, manifest_target_ids)
    if set_records:
        # Build sets in dependency order so an assumption always refers to a
        # lemma that is already a graph node.
        lemma_items.sort(key=lambda item: lemma_cfg[_sanitize(str(item.get("id", "")), "lemma")]["order"])
        target_items.sort(key=lambda item: target_cfg[_sanitize(str(item.get("id", "")), "target")]["order"])

    def assumed_premises(item_id: str, cfg: dict[str, dict[str, Any]]) -> list[dict[str, str]]:
        conf = cfg.get(item_id, {})
        out: list[dict[str, str]] = []
        for assumed in conf.get("assumes", []):
            premise = prem(assumed)
            if premise not in out:
                out.append(premise)
        return out

    for item in lemma_items:
        lid = _sanitize(str(item.get("id", "")), "lemma")
        if lid in by_id:
            raise PcdError(f"decomposition: duplicate lemma id {lid!r}")
        prop_name = str(item.get("property", ""))
        index, prop = _property_index(context, prop_name)
        if prop_name in property_nodes:
            raise PcdError(f"decomposition: property {prop_name!r} is used more than once")
        symbol = f"l_{index}"
        guarantee = f"L_{_sanitize(lid, str(index))}"
        cfg = lemma_cfg.get(lid, {})
        requires = [prem(str(x)) for x in item.get("requires", [])]
        for premise in assumed_premises(lid, lemma_cfg):
            if premise not in requires:
                requires.append(premise)
        backend = str(item.get("backend") or cfg.get("backend") or "cill")
        if backend not in _SET_METHODS:
            raise PcdError(f"decomposition: lemma {lid!r} has unsupported backend {backend!r}")
        node = _replay_node(
            node_id=f"lemma.{lid}",
            prop=prop,
            statement=str(item.get("statement", f"lemma {prop_name}")),
            role=str(item.get("role", "invariant")),
            kind=str(item.get("kind", "inductive")),
            phase=str(item.get("phase", "loop")),
            requires=requires,
            guarantee=guarantee,
            symbol=symbol,
            timeout_s=timeout_s,
            helper={"kind": "monitor", "note": str(item.get("note", "decomposition lemma"))},
            backend=backend,
            engine=str(item.get("engine") or "ric3"),
        )
        add_node(node)
        symbols[lid] = symbol
        guarantee_by_node[node["id"]] = guarantee
        node_id_by_manifest[lid] = node["id"]
        property_nodes[prop_name] = lid

    target_ids: list[str] = []
    for item in target_items:
        tid = _sanitize(str(item.get("id", "")), "target")
        if tid in by_id:
            raise PcdError(f"decomposition: duplicate target id {tid!r}")
        prop_name = str(item.get("property", ""))
        index, prop = _property_index(context, prop_name)
        if prop_name in property_nodes:
            raise PcdError(f"decomposition: property {prop_name!r} is used more than once")
        symbol = f"t_{index}"
        guarantee = f"T_{_sanitize(tid, str(index))}"
        cfg = target_cfg.get(tid, {})
        requires = [prem(str(x)) for x in item.get("requires", [])]
        for premise in assumed_premises(tid, target_cfg):
            if premise not in requires:
                requires.append(premise)
        backend = str(item.get("backend") or cfg.get("backend") or "cill")
        if backend not in _SET_METHODS:
            raise PcdError(f"decomposition: target {tid!r} has unsupported backend {backend!r}")
        node = _replay_node(
            node_id=f"target.{tid}",
            prop=prop,
            statement=str(item.get("statement", f"target {prop_name}")),
            role="observe",
            kind="replay",
            phase=str(item.get("phase", "loop")),
            requires=requires,
            guarantee=guarantee,
            symbol=symbol,
            timeout_s=timeout_s,
            helper=None,
            backend=backend,
            engine=str(item.get("engine") or "ric3"),
        )
        add_node(node)
        symbols[tid] = symbol
        guarantee_by_node[node["id"]] = guarantee
        node_id_by_manifest[tid] = node["id"]
        property_nodes[prop_name] = tid
        target_ids.append(tid)

    if not target_ids:
        raise PcdError("decomposition: manifest declares no targets")
    model_props = context["model"].get("properties", [])
    missing = [
        str(p.get("name"))
        for p in model_props
        if str(p.get("name")) not in property_nodes
    ]
    if missing:
        raise PcdError(
            "decomposition: manifest does not bind every model property: "
            + ", ".join(missing)
        )

    cut_nodes: list[str] = []
    cut_members: set[str] = set()
    for item in spec.get("cuts", []):
        cid = _sanitize(str(item.get("id", "")), "cut")
        cut_id = f"cut.{cid}"
        if cut_id in by_id:
            raise PcdError(f"decomposition: duplicate cut id {cid!r}")
        members = [str(x) for x in item.get("members", [])]
        if not members:
            raise PcdError(f"decomposition: cut {cid!r} has no members")
        for member in members:
            if member not in node_id_by_manifest:
                raise PcdError(f"decomposition: cut {cid!r} names unknown member {member!r}")
        reqs = [prem(member) for member in members]
        member_symbols = [symbols[member] for member in members]
        goal_expr = _conjunction(member_symbols)
        guarantee = f"C_{_sanitize(cid, 'cut')}"
        smt = expr_mod.canonical_script(member_symbols, goal_expr)

        def refs(part: str) -> list[dict[str, str]]:
            ids = [str(x) for x in item.get(part, [])]
            for ref_id in ids:
                if ref_id not in members:
                    raise PcdError(
                        f"decomposition: cut {cid!r} {part} fact {ref_id!r} is not a member"
                    )
            return [prem(x) for x in ids]

        cut_record = {
            "boundary": str(item.get("boundary", f"decomposition cut {cid}")),
            "entry": refs("entry"),
            "step": refs("step"),
            "exit": refs("exit"),
            "link": refs("link"),
        }
        if not cut_record["link"]:
            raise PcdError(f"decomposition: cut {cid!r} has no link facts")
        node = {
            "id": cut_id,
            "role": "interface",
            "kind": "linear",
            "phase": "loop",
            "statement": str(
                item.get(
                    "statement",
                    f"checked cut {cid}: {cut_record['boundary']}",
                )
            ),
            "requires": reqs,
            "provides": [{"name": guarantee, "expr": goal_expr, "sort": "Bool"}],
            "certificate_hint": {
                "evidence": "CHECKED",
                "format": "smt-implication",
                "checker": "z3-implication",
                "goal": guarantee,
                "payload": {
                    "premises": reqs,
                    "goal": guarantee,
                    "smt2": smt,
                    "timeout_ms": 30000,
                },
            },
            "cut": cut_record,
        }
        add_node(node)
        cut_nodes.append(cut_id)
        guarantee_by_node[cut_id] = guarantee
        cut_members.update(members)

    root_spec = spec.get("root", {})
    case_targets = case.get("targets", [])
    if len(case_targets) != 1:
        raise PcdError(
            "decomposition: the lemma-chain planner currently requires exactly one case target"
        )
    target_id = str(case_targets[0]["id"])
    if target_id in by_id:
        raise PcdError(f"decomposition: target root id {target_id!r} collides with a node")

    # Every target is a direct root premise.  Helpers are either consumed by a
    # cut or, when the manifest has no cut for them, by the root as well.  The
    # goal is always the conjunction of target properties, never a helper.
    root_req_ids: list[str] = []
    for tid in target_ids:
        root_req_ids.append(node_id_by_manifest[tid])
    for lid in list(symbols) + cut_nodes:
        if lid in target_ids or lid in cut_nodes:
            continue
        if lid in cut_members:
            continue
        actual = node_id_by_manifest.get(lid)
        if actual is not None:
            root_req_ids.append(actual)
    root_req_ids.extend(cut_nodes)
    # Preserve a stable, meaningful order: targets, then helpers, then cuts.
    seen: set[str] = set()
    ordered: list[str] = []
    for rid in root_req_ids:
        if rid not in seen:
            seen.add(rid)
            ordered.append(rid)
    root_reqs = [prem(rid) for rid in ordered]
    target_exprs = [symbols[tid] for tid in target_ids]
    goal_expr = _conjunction(target_exprs)
    goal_name = "GOAL"
    smt = expr_mod.canonical_script(
        [by_id[rid]["provides"][0]["expr"] for rid in ordered],
        goal_expr,
    )
    root_node = {
        "id": target_id,
        "role": "compose",
        "kind": "linear",
        "phase": "any",
        "statement": str(
            root_spec.get(
                "statement",
                "closed decomposition: target properties follow from the checked lemma chain",
            )
        ),
        "requires": root_reqs,
        "provides": [{"name": goal_name, "expr": goal_expr, "sort": "Bool"}],
        "certificate_hint": {
            "evidence": "CHECKED",
            "format": "smt-implication",
            "checker": "z3-implication",
            "goal": goal_name,
            "payload": {
                "premises": root_reqs,
                "goal": goal_name,
                "smt2": smt,
                "timeout_ms": 30000,
            },
        },
    }
    nodes.append(root_node)

    target_prop = {
        "id": target_id,
        "goal": goal_name,
        "requires": root_reqs,
        "tcb": [],
        "composition_hint": {
            "mode": "CHECKED",
            "checker": "z3-implication",
            "payload": {
                "premises": root_reqs,
                "goal": goal_name,
                "smt2": smt,
                "timeout_ms": 30000,
            },
            "notes": "root consumes the declared lemma/cut chain",
        },
    }

    return {
        "schema_version": "pcd-proposal/0.1",
        "case": case["id"],
        "planner": {
            "name": "decompose",
            "version": "0.1",
            "context_sha256": context_sha256,
        },
        "nodes": nodes,
        "targets": [target_prop],
        "metadata": {
            "rationale": (
                "declared lemma chain with checked cuts and per-set engine methods"
                if set_records
                else "declared lemma chain with checked cuts; engine evidence unchanged"
            ),
            "manifest": spec.get("id"),
            "sets": set_records,
        },
    }
