#!/usr/bin/env python3
"""Run a curated benchmark test list.

The lists are generated by ``make_testlist.py``:

* ``--tier smoke``    10 cases, family-related quick regression;
* ``--tier core``     40 cases (smoke + core);
* ``--tier extended`` 101 non-ALT OPS active cases;
* ``--tier full``     5 official PCD/riscv-formal fullcheck imports;
* ``--tier all``      extended + full (106 cases).

Reduced cases run through their own ``./run.sh`` (``ric3 build`` plus a model
hash).  The full/official cases live under ``automation/pcd/cases/official``
and run through their ``build/build.sh`` recipe.  This is a build/readiness
suite; proof overlays and certificates live in ``automation/decomp/``.

Usage:
    python3 run_testlist.py --tier smoke
    python3 run_testlist.py --tier core --jobs 4
    python3 run_testlist.py --tier full --timeout 900
    python3 run_testlist.py --tier smoke --dry-run
"""

import argparse
import csv
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO = HERE.parent


def load_rows(tier):
    active = list(csv.DictReader(open(HERE / "testlist.csv")))
    full = list(csv.DictReader(open(HERE / "testlist_full.csv")))
    if tier == "smoke":
        return [r for r in active if r["tier"] == "smoke"]
    if tier == "core":
        return [r for r in active if r["tier"] in ("smoke", "core")]
    if tier == "extended":
        return active
    if tier == "full":
        return full
    if tier == "all":
        return active + full
    raise SystemExit("unknown tier: %s" % tier)


def run_case(row, timeout):
    case_dir = REPO / row["path"]
    if row["family"] == "official":
        script = case_dir / "build" / "build.sh"
        if not script.exists():
            return row, "FAIL", 0.0, "missing %s" % script
        cmd = ["sh", "build/build.sh"]
    else:
        script = case_dir / "run.sh"
        if not script.exists():
            return row, "FAIL", 0.0, "missing %s" % script
        cmd = ["./run.sh"] if os.access(script, os.X_OK) else ["sh", "./run.sh"]

    started = time.monotonic()
    try:
        proc = subprocess.run(
            cmd, cwd=case_dir, stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT, text=True, timeout=timeout,
        )
    except subprocess.TimeoutExpired as exc:
        out = exc.stdout or ""
        if isinstance(out, bytes):
            out = out.decode("utf-8", "replace")
        return row, "TIMEOUT", time.monotonic() - started, out
    elapsed = time.monotonic() - started
    if proc.returncode == 0:
        return row, "PASS", elapsed, proc.stdout
    return row, "FAIL", elapsed, proc.stdout


def tail(text, lines=12):
    return "\n".join(text.splitlines()[-lines:])


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tier", default="smoke",
                    choices=("smoke", "core", "extended", "full", "all"))
    ap.add_argument("--family", default=None,
                    help="comma-separated family filter, e.g. picorv32,nerv")
    ap.add_argument("--jobs", type=int, default=4,
                    help="parallel cases (default: 4)")
    ap.add_argument("--timeout", type=int, default=600,
                    help="per-case timeout in seconds (default: 600)")
    ap.add_argument("--dry-run", action="store_true",
                    help="print the selected cases without building")
    args = ap.parse_args()

    rows = load_rows(args.tier)
    if args.family:
        families = {f.strip() for f in args.family.split(",") if f.strip()}
        rows = [r for r in rows if r["family"] in families]
    if not rows:
        raise SystemExit("no cases selected")

    print("suite: %s (%d cases)" % (args.tier, len(rows)))
    if args.dry_run:
        for r in rows:
            print("  %-10s %-24s %s" % (r["family"], r["case"], r["path"]))
        return 0

    results = []
    started = time.monotonic()
    with ThreadPoolExecutor(max_workers=min(args.jobs, len(rows))) as pool:
        futures = {pool.submit(run_case, row, args.timeout): row for row in rows}
        for fut in as_completed(futures):
            row, status, elapsed, output = fut.result()
            key = "%s/%s" % (row["family"], row["case"])
            print("%-7s %-28s %7.1fs" % (status, key, elapsed))
            if status != "PASS":
                print(tail(output))
            results.append((row, status, elapsed))

    elapsed = time.monotonic() - started
    ok = sum(1 for _, s, _ in results if s == "PASS")
    fail = sum(1 for _, s, _ in results if s == "FAIL")
    timeout = sum(1 for _, s, _ in results if s == "TIMEOUT")
    print("\nsummary: %d pass, %d fail, %d timeout  (%.1fs)" % (
        ok, fail, timeout, elapsed))
    return 0 if fail == 0 and timeout == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
